#!/usr/bin/env node
// samples-table — the samples page's comparison table, generated from the
// archives themselves (docs/runs/*): each run's manifest, the forum and
// timeline its export embeds, and which files the archive ships. The site
// has no build step, so the table lives in docs/samples.html between two
// markers; this tool rewrites that block, and --check (also run by the
// site test) fails when the page and the archives disagree.
//
// It exists because the page drifted: hand-copied counts ("four complete
// runs" beside seven cards), a provenance list that missed a run, and a
// card that said "no filing" about a run whose filings were refused.
// Numbers a reader compares across runs come from the data, not prose.
//
// Curation is not record: a run's optional `sample.json` beside its archive
// says how the site presents it — `label` (a display name), `archived`
// (`{ supersededBy, why }`: kept, listed, no longer featured), and
// `provenance` (a correction the manifest cannot carry, because the
// manifest is the record and is never edited).
//
//   node tools/samples-table.mjs            rewrite the block in place
//   node tools/samples-table.mjs --check    exit 1 when the block is stale
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { parseEmbeddedArchive } from './community-brief.mjs';
import { GATE_RE } from './run-manifest.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- runs-table:start — generated by tools/samples-table.mjs from docs/runs/*; edit the tool, not this block -->';
const END = '<!-- runs-table:end -->';

const esc = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const num = (n) => (Number.isFinite(n) ? n.toLocaleString('en-US') : '—');

/** One row per published archive, read from the archive alone. */
export function samplesRows(docsDir = join(ROOT, 'docs')) {
  const runsDir = join(docsDir, 'runs');
  const rows = [];
  for (const name of readdirSync(runsDir).sort()) {
    const dir = join(runsDir, name);
    const html = readdirSync(dir).find((f) => f.endsWith('.html'));
    if (!html || !existsSync(join(dir, 'run.json'))) continue;
    const run = JSON.parse(readFileSync(join(dir, 'run.json'), 'utf8'));
    const data = parseEmbeddedArchive(readFileSync(join(dir, html), 'utf8'));
    if (!data) throw new Error(`samples-table: ${name}/${html} embeds no archive data`);
    const seats = Array.isArray(run.seats) && run.seats.length ? run.seats.map((s) => s.model) : Object.values(run.model?.members ?? {});
    const hears = data.timeline.filter((e) => e.type === 'act' && e.text === 'judicature_hear');
    const chainsDir = join(dir, 'chains');
    const curation = existsSync(join(dir, 'sample.json')) ? JSON.parse(readFileSync(join(dir, 'sample.json'), 'utf8')) : {};
    rows.push({
      name,
      href: `runs/${name}/${html}`,
      charter: run.charter ?? name,
      label: curation.label ?? run.charter ?? name,
      archived: curation.archived ?? null,
      provenanceNote: curation.provenance ?? null,
      runTag: run.runTag ?? '',
      endedAt: run.endedAt ?? '',
      seats: seats.length,
      routes: new Set(seats.filter(Boolean)).size,
      rounds: run.rounds,
      roundBudget: run.budgets?.rounds ?? null,
      tokens: run.tokens,
      tokenCap: run.budgets?.tokenCap ?? null,
      endReason: run.endReason ?? '—',
      gates: data.forum
        .map((p) => ({ id: p.id, m: GATE_RE.exec(String(p.text ?? '').trimStart()) }))
        .filter(({ m }) => m)
        .map(({ id, m }) => ({ id, gate: m[1] })),
      filings: {
        tried: hears.length,
        landed: data.actOutcomes ? hears.filter((e) => e.outcome === 'ok').length : null,
      },
      loopguard: data.timeline.filter((e) => e.type === 'notice' && /LoopGuard/.test(String(e.text ?? ''))).length,
      actOutcomes: data.actOutcomes === true,
      chains: existsSync(chainsDir) ? readdirSync(chainsDir).filter((f) => f.endsWith('.chain')).length : 0,
      code: run.code?.commit ? { commit: String(run.code.commit).slice(0, 7), dirty: run.code.dirty === true, foreign: run.code.foreignPackages?.length ?? 0 } : null,
    });
  }
  return rows.sort((a, b) => String(a.endedAt).localeCompare(String(b.endedAt)));
}

/** The table block, markers included. Nine columns, so it fits the
 *  page's content width; the last one carries what the archive itself
 *  ships — outcomes, chains, code — the honesty axis of the comparison. */
export function renderSamplesTable(rows) {
  const L = [START];
  L.push('<div class="table-wrap">');
  L.push('<table class="runs-table">');
  L.push('<thead><tr><th>run</th><th class="num">seats</th><th class="num">rounds</th><th class="num">tokens</th><th>ended by</th><th>gate posts</th><th>filings</th><th class="num">LoopGuard</th><th>the archive ships</th></tr></thead>');
  L.push('<tbody>');
  for (const r of rows) {
    const byGate = new Map();
    for (const g of r.gates) byGate.set(g.gate, [...(byGate.get(g.gate) ?? []), g.id]);
    const gates = byGate.size
      ? [...byGate].map(([gate, ids]) => `${esc(gate)} ${ids.map((id) => `<a href="${esc(r.href)}#${esc(id)}">${esc(id)}</a>`).join(' ')}`).join('<br>')
      : '<span class="muted">none</span>';
    const filings = r.filings.tried === 0 ? '<span class="muted">none tried</span>'
      : r.filings.landed == null ? `${r.filings.tried} tried<br><small>landed: not recorded</small>`
        : `${r.filings.tried} tried<br><small>${r.filings.landed} landed</small>`;
    // "token cap: 2000000" repeats the cap the tokens cell already shows
    const endedBy = /^token cap\b/.test(r.endReason) ? 'token cap' : r.endReason;
    const ships = [
      r.actOutcomes ? 'act outcomes' : '<span class="muted">no act outcomes</span>',
      r.chains ? `${r.chains} signed chains` : '<span class="muted">no chains</span>',
      r.code ? `code <code>${esc(r.code.commit)}</code>${r.code.dirty ? ' <span class="warn">dirty</span>' : ''}${r.code.foreign ? ` <span class="warn">${r.code.foreign} foreign</span>` : ''}${r.provenanceNote ? ` <span class="warn" title="${esc(r.provenanceNote)}">misrecorded</span>` : ''}` : '<span class="muted">no code commit</span>',
    ].join('<br>');
    L.push('<tr>' +
      `<td><a href="${esc(r.href)}" target="_blank" rel="noreferrer">${esc(r.label)}</a><br><small>${esc(String(r.endedAt).slice(0, 10))} · <span class="run-id">${esc(r.runTag)}</span>${r.archived ? ' · archived' : ''}</small></td>` +
      `<td class="num">${r.seats}${r.routes > 1 ? `<br><small>${r.routes} routes</small>` : ''}</td>` +
      `<td class="num">${num(r.rounds)}${r.roundBudget != null ? `<br><small>of ${num(r.roundBudget)}</small>` : ''}</td>` +
      `<td class="num">${num(r.tokens)}${r.tokenCap != null ? `<br><small>cap ${num(r.tokenCap)}</small>` : ''}</td>` +
      `<td>${esc(endedBy)}</td>` +
      `<td class="gates">${gates}</td>` +
      `<td>${filings}</td>` +
      `<td class="num">${r.loopguard}</td>` +
      `<td class="ships">${ships}</td>` +
      '</tr>');
  }
  L.push('</tbody>');
  L.push('</table>');
  L.push('</div>');
  L.push(END);
  return L.join('\n');
}

/** Replace the marked block in the page; throws when the markers are missing. */
export function syncSamplesTable(page, table) {
  const a = page.indexOf(START);
  const b = page.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error('samples-table: docs/samples.html has no runs-table markers');
  return page.slice(0, a) + table + page.slice(b + END.length);
}

function main() {
  const pagePath = join(ROOT, 'docs', 'samples.html');
  const page = readFileSync(pagePath, 'utf8');
  const next = syncSamplesTable(page, renderSamplesTable(samplesRows()));
  if (process.argv.includes('--check')) {
    if (next === page) { console.log('samples-table: in sync with docs/runs'); return; }
    console.error('samples-table: docs/samples.html is stale — run node tools/samples-table.mjs');
    process.exitCode = 1;
    return;
  }
  if (next !== page) writeFileSync(pagePath, next);
  console.log(`samples-table: ${next === page ? 'already in sync' : 'rewrote the block in docs/samples.html'}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
